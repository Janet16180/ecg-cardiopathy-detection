def validate_policy(policy: dict[str, Any]) -> None:
    """Reject policy changes that would admit automatic labels or unapproved sources."""
    if not policy.get("policy_version") or policy["ptbxl"]["unvalidated_automatic_or_unknown"] != "exclude":
        raise ValueError("A versioned explicit human-label policy is required")
    if (policy["ptbxl"]["human_validated_rank"] != 1 or
            policy["ptbxl"]["physician_origin_unvalidated_rank"] != 2):
        raise ValueError("PTB evidence ranks differ from the approved protocol")
    expected = {"ningbo", "chapman_shaoxing", "georgia", "cpsc_2018", "cpsc_2018_extra"}
    if set(policy["sources"]) != expected:
        raise ValueError("Only the approved human-read Challenge sources are admitted")
    for item in policy["sources"].values():
        if item["rank"] not in (0, 1, 2) or not item["evidence"] or not item["reference"]:
            raise ValueError("Missing source annotation evidence")


def normalized_sex(rows: pd.DataFrame) -> pd.Series:
    """Normalize only documented sex encodings for conservative copy-conflict checks."""
    values = rows["sex"].astype(str).str.lower()
    result = values.map({"male": "M", "female": "F", "m": "M", "f": "F"}).fillna("")
    ptb = rows["source"].eq("ptbxl")
    result.loc[ptb] = values.loc[ptb].map({"0": "M", "0.0": "M", "1": "F", "1.0": "F"}).fillna("")
    return result


def exclusion_reasons(rows: pd.DataFrame, references: pd.DataFrame) -> pd.Series:
    """Reject invalid labels, quality failures and every observed held-out identity match."""
    checks = {
        "not_training": ~rows["split"].eq("train"),
        "signal_quality": ~rows["quality_passed"].eq(True),  # noqa: E712
        "undefined_target": ~rows["target"].isin([0, 1]),
        "unadmitted_label_evidence": ~rows["label_evidence_rank"].isin([0, 1, 2]),
        "supervised_ineligible": ~rows["supervised_admitted"].eq(True),  # noqa: E712
        "missing_canonical_hash": ~rows["signal_sha256"].str.fullmatch(r"[0-9a-f]{64}", na=False),
        "heldout_record": rows["record_id"].isin(set(references["record_id"])),
        "heldout_patient": rows["patient_id"].ne("") & rows["patient_id"].isin(
            set(references.loc[references["patient_id"].ne(""), "patient_id"])),
        "heldout_canonical_window": rows["signal_sha256"].isin(
            set(references.loc[references["canonical_sha256"].ne(""), "canonical_sha256"])),
        "heldout_full_signal": rows["full_signal_sha256"].ne("") & rows["full_signal_sha256"].isin(
            set(references.loc[references["full_signal_sha256"].ne(""), "full_signal_sha256"])),
    }
    flags = pd.DataFrame(checks, index=rows.index)
    return flags.apply(lambda row: ";".join(row.index[row]), axis=1)


def deduplicate_candidates(rows: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Drop conflicting exact copies or retain one copy by evidence rank and stable record identity."""
    if rows["record_id"].eq("").any() or rows["record_id"].duplicated().any():
        raise ValueError("Candidate record identities are missing or duplicated")
    ordered = rows.sort_values(["label_evidence_rank", "record_id"], kind="stable").copy()
    groups = ordered.groupby("signal_sha256", sort=False)
    target_conflict = groups["target"].transform("nunique") > 1
    known_sex = ordered["sex_normalized"].replace("", pd.NA)
    sex_counts = known_sex.groupby(ordered["signal_sha256"]).transform("nunique")
    conflicts = target_conflict | (sex_counts > 1)
    copies = ordered.duplicated("signal_sha256", keep="first")
    reason = pd.Series("", index=ordered.index)
    reason.loc[copies] = "duplicate_copy"
    reason.loc[conflicts] = "duplicate_conflicting_target_or_known_sex"
    rejected = ordered.loc[reason.ne(""), ["record_id", "source"]].assign(reason=reason[reason.ne("")])
    return ordered.loc[reason.eq("")].reset_index(drop=True), rejected.reset_index(drop=True)


def admit_candidates(ptb: pd.DataFrame, challenge: pd.DataFrame,
                      references: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Normalize verified source tables, apply held-out exclusions and resolve exact copies."""
    ptb = ptb.assign(supervised_admitted=True)
    rows = pd.concat([ptb, challenge], ignore_index=True, sort=False).fillna({
        name: "" for name in MANIFEST_COLUMNS if name not in {
            "age", "age_lower_bound", "target", "quality_passed", "age_right_censored", "age_missing",
            "patient_identity_known", "label_evidence_rank",
        }
    })
    rows["sex_normalized"] = normalized_sex(rows)
    known = rows["patient_identity_known"].eq(True)  # noqa: E712
    if (known & rows["patient_id"].eq("")).any():
        raise ValueError("Known candidate patient identities cannot be empty")
    reasons = exclusion_reasons(rows, references)
    ledger = rows.loc[reasons.ne(""), ["record_id", "source"]].assign(reason=reasons[reasons.ne("")])
    admitted = rows.loc[reasons.eq(""), list(MANIFEST_COLUMNS)].copy()
    admitted["target"] = admitted["target"].astype(int)
    admitted, duplicates = deduplicate_candidates(admitted)
    return admitted, pd.concat([ledger, duplicates], ignore_index=True)


def summarize(rows: pd.DataFrame) -> dict[str, Any]:
    """Describe actual records, label provenance and exact ages without treating censored bounds as ages."""
    exact = pd.to_numeric(rows.loc[rows["age_interpretation"] == "exact", "age"])
    age_summary = {
        "exact_count": len(exact), "missing_count": int(rows["age_missing"].sum()),
        "right_censored_over_89_count": int(rows["age_right_censored"].sum()),
        "exact_min": float(exact.min()) if len(exact) else None,
        "exact_max": float(exact.max()) if len(exact) else None,
        "exact_mean": float(exact.mean()) if len(exact) else None,
        "exact_median": float(exact.median()) if len(exact) else None,
        "exact_18_25_count": int(exact.between(18, 25).sum()),
        "exact_under_18_count": int((exact < 18).sum()),
        "selection_uses_censored_lower_bound": True,
    }
    return {
        "records": len(rows), "target": rows["target"].value_counts().sort_index().to_dict(),
        "sources": rows["source"].value_counts().sort_index().to_dict(),
        "families": rows["family"].value_counts().sort_index().to_dict(),
        "label_evidence_rank": rows["label_evidence_rank"].value_counts().sort_index().to_dict(),
        "label_evidence": rows["label_evidence"].value_counts().sort_index().to_dict(),
        "known_patients": rows.loc[rows["patient_id"].ne(""), "patient_id"].nunique(),
        "records_without_patient_identity": int(rows["patient_id"].eq("").sum()),
        "source_target_counts": rows.groupby(["source", "target"]).size().rename("records").reset_index(
        ).to_dict("records"),
        "age": age_summary,
    }


def cohort_overlap(first: pd.DataFrame, second: pd.DataFrame) -> dict[str, int]:
    """Count observed shared records, waveform windows and known patients between training cohorts."""
    return {name: len((set(first[column]) & set(second[column])) - {""}) for name, column in (
        ("records", "record_id"), ("canonical_windows", "signal_sha256"), ("known_patients", "patient_id"),
    )}


def evaluation_overlap(rows: pd.DataFrame, references: pd.DataFrame) -> dict[str, int]:
    """Measure observed evaluation intersections independently from the admission ledger."""
    columns = {
        "records": ("record_id", "record_id"), "known_patients": ("patient_id", "patient_id"),
        "canonical_windows": ("signal_sha256", "canonical_sha256"),
        "full_signals": ("full_signal_sha256", "full_signal_sha256"),
    }
    return {name: len((set(rows[left]) & set(references[right])) - {""})
            for name, (left, right) in columns.items()}


def verify_unchanged(input_root: Path, hashes: dict[str, str]) -> None:
    """Fail if an evidence artifact changes after its admission check."""
    for name, digest in hashes.items():
        if sha256_file(input_root / relative_path(name)) != digest:
            raise ValueError(f"Assembly input changed: {name}")


def recipe_snapshot() -> dict[str, str]:
    """Capture policy, protocol and source bytes before any assembly interpretation or selection."""
    paths = [POLICY, PROTOCOL, *(Path(name) for name in SOURCE_FILES)]
    return {input_stored(path): sha256_file(ROOT / path) for path in paths}


def verify_recipe(hashes: dict[str, str]) -> None:
    """Reject concurrent policy, protocol or implementation changes before publishing completion."""
    for name, digest in hashes.items():
        if sha256_file(ROOT / name) != digest:
            raise ValueError(f"Assembly recipe changed: {name}")


def write_artifacts(destination: Path, tables: dict[str, pd.DataFrame],
                    summary: dict[str, Any]) -> dict[str, str]:
    """Write new manifest artifacts atomically without replacing an existing cohort directory."""
    destination.mkdir(parents=True, exist_ok=False)
    hashes = {}
    for name, table in tables.items():
        temporary = destination / (name + ".tmp")
        table.to_csv(temporary, index=False)
        os.replace(temporary, destination / name)
        hashes[name] = sha256_file(destination / name)
    write_json_atomic(destination / "summary.json", summary, sort_keys=True)
    hashes["summary.json"] = sha256_file(destination / "summary.json")
    return hashes


def assemble(input_root: Path, output: Path, size: int = 25_000, seed: int = 42) -> dict[str, Any]:
    """
    Assemble both cohorts only after completed reconstruction and exclusion gates pass.

    Parameters
    ----------
    input_root : Path
        Shared checkout containing verified local recovery inputs. No waveform is opened.
    output : Path
        New directory relative to that checkout; existing directories are refused.
    size : int
        Cohort ceiling, from two through 25,000. Eligibility never weakens to fill it.
    seed : int
        Existing selector's deterministic record-ID tie-breaking seed.

    Returns
    -------
    dict[str, Any]
        Completion receipt with exact evidence, source, policy and artifact hashes.
    """
    if not 2 <= size <= 25_000:
        raise ValueError("Use a ceiling of two through 25,000 records")
    output = relative_path(output)
    destination = input_root / output
    if destination.exists():
        raise FileExistsError(destination)
    recipe_hashes = recipe_snapshot()
    policy = json.loads((ROOT / POLICY).read_text())
    validate_policy(policy)
    verify_recipe(recipe_hashes)
    references, hashes = read_references(input_root)
    ptb, ptb_hashes, ptb_counts, initial_ledger = load_ptb(input_root, policy)
    challenge, challenge_hashes, challenge_counts = load_challenge(input_root, policy)
    hashes.update(ptb_hashes)
    hashes.update(challenge_hashes)
    candidates, ledger = admit_candidates(ptb, challenge, references)
    ledger = pd.concat([initial_ledger, ledger], ignore_index=True)
    younger = select_cohort(candidates, size, seed, prefer_young=True)
    all_age = select_cohort(candidates, size, seed, prefer_young=False)
    if any(rows["target"].nunique() != 2 for rows in (younger, all_age)):
        raise ValueError("Both admitted classes must be represented in each cohort")
    summary = {
        "candidates": summarize(candidates), "younger": summarize(younger), "all_age": summarize(all_age),
        "overlap_between_training_cohorts": cohort_overlap(younger, all_age),
        "excluded_records": len(ledger), "exclusion_combinations": ledger["reason"].value_counts().to_dict(),
        "ptb_recovery_admission": ptb_counts, "challenge_recovery_admission": challenge_counts,
        "evaluation_overlap_after_admission": evaluation_overlap(candidates, references),
    }
    verify_unchanged(input_root, hashes)
    verify_recipe(recipe_hashes)
    source_hashes = {input_stored(Path(name)): recipe_hashes[input_stored(Path(name))]
                     for name in SOURCE_FILES}
    tables = {"candidates.csv": candidates, "exclusions.csv": ledger,
              "younger.csv": younger, "all_age.csv": all_age}
    outputs = write_artifacts(destination, tables, summary)
    verify_unchanged(input_root, hashes)
    verify_recipe(recipe_hashes)
    receipt = {
        "complete": True, "scope": "new_supervised_age_label_cohorts", "size_ceiling": size, "seed": seed,
        "original_split_sha256": SPLIT_SHA256, "policy_version": policy["policy_version"],
        "policy_path": input_stored(POLICY), "policy_sha256": recipe_hashes[input_stored(POLICY)],
        "protocol_path": input_stored(PROTOCOL), "protocol_sha256": recipe_hashes[input_stored(PROTOCOL)],
        "recipe_sha256": recipe_hashes,
        "input_sha256": hashes, "source_sha256": source_hashes,
        "artifacts": {input_stored(output / name): digest for name, digest in outputs.items()},
        "summary": summary, "waveforms_read": 0, "model_scores_read_or_computed": 0,
        "limitation": "New evidence-ranked selections, not byte-identical historical cohorts; exact-copy "
                      "and known-patient checks cannot establish patient independence without patient IDs",
    }
    write_json_atomic(destination / "receipt.json", receipt, sort_keys=True)
    return receipt
