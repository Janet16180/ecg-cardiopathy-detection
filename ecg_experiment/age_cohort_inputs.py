def relative_path(value: Path | str) -> Path:
    """Require a portable repository-relative artifact path without traversal."""
    path = Path(value)
    if path.is_absolute() or ".." in path.parts or path == Path("."):
        raise ValueError("Artifact paths must be nonempty and repository-relative")
    return path


def stored(value: Path | str) -> str:
    """Use the shared path helper independently of the checkout holding local data."""
    return to_stored(ROOT / relative_path(value))


def read_receipt(input_root: Path, path: Path, scope: str) -> tuple[dict[str, Any], dict[str, str]]:
    """Require a completed receipt with the requested scope and unchanged frozen quality policy."""
    path = relative_path(path)
    receipt = json.loads((input_root / path).read_text())
    if receipt.get("complete") is not True or receipt.get("scope") != scope:
        raise ValueError(f"Incomplete or wrong-scope receipt: {path}")
    if scope == "training_quality":
        expected = sha256_file(ROOT / "ecg_experiment/ecg_quality.py")
        if receipt.get("source_sha256", {}).get("ecg_experiment/ecg_quality.py") != expected:
            raise ValueError("Signal-quality policy differs from the frozen local policy")
    return receipt, {stored(path): sha256_file(input_root / path)}


def verified_table(input_root: Path, path: Path, scope: str,
                   original_split: bool) -> tuple[pd.DataFrame, dict[str, Any], dict[str, str]]:
    """Load only a receipt-bound table after its completion and exact split gates pass."""
    receipt, hashes = read_receipt(input_root, path, scope)
    if original_split and receipt.get("original_split_sha256") != SPLIT_SHA256:
        raise ValueError("Original Challenge split receipt gate failed")
    table = relative_path(receipt.get("table_path", receipt.get("quality_path", "")))
    digest = receipt.get("table_sha256", receipt.get("quality_sha256"))
    if sha256_file(input_root / table) != digest:
        raise ValueError(f"Receipt-bound table changed: {table}")
    hashes[stored(table)] = digest
    return pd.read_csv(input_root / table, dtype=str, keep_default_na=False), receipt, hashes


def read_references(input_root: Path) -> tuple[pd.DataFrame, dict[str, str]]:
    """Require complete mechanical references with identity and hash fields, without labels."""
    rows, receipt, hashes = verified_table(input_root, REFERENCES, "mechanical_reference_recovery", True)
    if receipt.get("coverage_complete") is not True:
        raise ValueError("Held-out reference coverage is incomplete")
    if not set(REFERENCE_COLUMNS) <= set(rows):
        raise ValueError("Held-out reference schema lacks required identities or hashes")
    if rows["record_id"].eq("").any() or rows["role"].eq("").any():
        raise ValueError("Reference identities and roles must be present")
    for name in ("canonical_sha256", "full_signal_sha256"):
        present = rows[name].ne("")
        if not rows.loc[present, name].str.fullmatch(r"[0-9a-f]{64}").all():
            raise ValueError("Malformed held-out waveform identity")
    if ((rows["canonical_sha256"] == "") & (rows["skip_reason"] == "")).any():
        raise ValueError("A missing canonical reference requires an explicit skip reason")
    if not receipt.get("records", len(rows)) == len(rows):
        raise ValueError("Reference receipt count differs from its table")
    known = parse_boolean(rows["patient_identity_known"])
    if (known & rows["patient_id"].eq("")).any():
        raise ValueError("Known reference patient identities cannot be empty")
    return rows[list(REFERENCE_COLUMNS)], hashes


def parse_boolean(values: pd.Series) -> pd.Series:
    """Interpret explicit true and false strings while rejecting ambiguous eligibility flags."""
    lowered = values.astype(str).str.lower()
    if not lowered.isin(["true", "false", "1", "0"]).all():
        raise ValueError("Eligibility flags must be explicit booleans")
    return lowered.isin(["true", "1"])


def normalize_age(raw: pd.Series, ptb: bool) -> pd.DataFrame:
    """Preserve exact, missing and PTB privacy-censored age interpretations separately."""
    numeric = pd.to_numeric(raw, errors="coerce")
    censored = numeric.ge(300) & np.isfinite(numeric) if ptb else pd.Series(False, index=raw.index)
    exact = numeric.between(0 if ptb else np.nextafter(0.0, 1.0), 120) & np.isfinite(numeric)
    age = numeric.where(exact).mask(censored, 90.0)
    return pd.DataFrame({
        "age_raw": raw, "age": age, "age_lower_bound": age,
        "age_right_censored": censored, "age_missing": age.isna(),
        "age_interpretation": np.select([censored, exact], ["right_censored_over_89", "exact"], "missing"),
    })


def read_selected_csv(path: Path, column: str, selected: set[str],
                      columns: tuple[str, ...]) -> pd.DataFrame:
    """Filter by administrative ID before parsing any selected-row annotation fields."""
    keys = pd.read_csv(path, usecols=[column], dtype=str, keep_default_na=False)[column]
    skip = list(keys.index[~keys.isin(selected)] + 1)
    return pd.read_csv(path, skiprows=skip, usecols=list(columns), dtype=str, keep_default_na=False)


def canonical_integral_id(value: str) -> str:
    """Normalize a positive integral source identifier exactly without binary floating-point conversion."""
    number = Decimal(value)
    if not number.is_finite() or number <= 0 or number != number.to_integral_value():
        raise ValueError("PTB identifiers must be positive exact integers")
    return str(int(number))


def canonical_ptb_identity(rows: pd.DataFrame) -> pd.DataFrame:
    """Align legacy .0 patient IDs and current integral IDs without changing source identity."""
    rows = rows.copy()
    rows["ecg_id"] = rows["ecg_id"].map(canonical_integral_id)
    rows["patient_id"] = rows["patient_id"].map(lambda value: canonical_integral_id(value) + ".0")
    if "strat_fold" in rows:
        rows["strat_fold"] = rows["strat_fold"].map(canonical_integral_id)
        if not pd.to_numeric(rows["strat_fold"]).between(1, 10).all():
            raise ValueError("Invalid official PTB fold")
    return rows


def ptb_roles(input_root: Path) -> tuple[pd.DataFrame, dict[str, str]]:
    """Bind current SCREEN-01 identities and explicitly restrict fitting to PTB folds one through seven."""
    receipt = json.loads((input_root / SCREEN_RECEIPT).read_text())
    expected = receipt.get("artifacts", {}).get(stored(SCREEN_ROWS))
    if (receipt.get("status") != "completed" or expected != SCREEN_SHA256 or
            sha256_file(input_root / SCREEN_ROWS) != SCREEN_SHA256):
        raise ValueError("Current SCREEN-01 PTB qualification gate failed")
    rows = pd.read_csv(input_root / SCREEN_ROWS, dtype=str, keep_default_na=False,
                       usecols=["ecg_id", "patient_id", "strat_fold", "filename_hr"])
    if rows["ecg_id"].duplicated().any():
        raise ValueError("Current PTB identities are duplicated")
    rows = canonical_ptb_identity(rows)
    return rows, {stored(SCREEN_ROWS): SCREEN_SHA256,
                  stored(SCREEN_RECEIPT): sha256_file(input_root / SCREEN_RECEIPT)}


def ptb_label_evidence(rows: pd.DataFrame, policy: dict[str, Any]) -> pd.DataFrame:
    """Prioritize record-level human validation, then documented physician-origin reports."""
    validated = rows["validated_by_human"].str.lower().isin(["true", "1"])
    physician = rows["initial_autogenerated_report"].str.lower().isin(["false", "0"])
    evidence = np.select([validated, physician], ["record_human_validated", "record_physician_origin"], "")
    ranks = np.select([validated, physician],
                      [policy["human_validated_rank"], policy["physician_origin_unvalidated_rank"]], -1)
    return rows.assign(label_evidence=evidence, label_evidence_rank=ranks,
                       label_evidence_reference=policy["reference"], label_evidence_scope="record")


def ptb_initial_exclusions(quality: pd.DataFrame, fit: set[str], defined: set[str]) -> pd.DataFrame:
    """Log administrative exclusions before parsing any non-fitting PTB record's label evidence."""
    reasons = pd.Series("", index=quality.index)
    reasons.loc[~quality["record_id"].isin(fit)] = "not_current_ptb_fit_role"
    undefined = quality["record_id"].isin(fit) & ~quality["record_id"].isin(defined)
    reasons.loc[undefined] = "undefined_original_target"
    selected = reasons.ne("")
    return quality.loc[selected, ["record_id"]].assign(source="ptbxl", reason=reasons[selected])


def load_ptb(input_root: Path, policy: dict[str, Any]
             ) -> tuple[pd.DataFrame, dict[str, str], dict[str, int], pd.DataFrame]:
    """Admit only verified PTB training labels and quality rows with current fitting roles."""
    quality, receipt, hashes = verified_table(input_root, PTB_QUALITY, "training_quality", False)
    roles, role_hashes = ptb_roles(input_root)
    hashes.update(role_hashes)
    if not receipt.get("historical_count_matches") or len(quality) != receipt["records"]:
        raise ValueError("PTB training recovery is not the completed historical selection")
    for name, digest in receipt["input_sha256"].items():
        if sha256_file(input_root / relative_path(name)) != digest:
            raise ValueError(f"PTB recovery input changed: {name}")
        hashes[stored(name)] = digest
    label_path = input_root / PTB_LABELS
    if hashlib.md5(label_path.read_bytes()).hexdigest() != PTB_LABELS_MD5:
        raise ValueError("Original PTB supervised manifest differs from its frozen bytes")
    hashes[stored(PTB_LABELS)] = sha256_file(label_path)
    fit = roles[pd.to_numeric(roles["strat_fold"]).between(1, 7)]
    allowed = set(fit["ecg_id"])
    labels = read_selected_csv(label_path, "ecg_id", allowed,
                               ("ecg_id", "patient_id", "filename_hr", "target"))
    metadata = read_selected_csv(input_root / PTB_RAW, "ecg_id", set(labels["ecg_id"]),
                                 PTB_EVIDENCE_COLUMNS)
    labels = canonical_ptb_identity(labels)
    metadata = canonical_ptb_identity(metadata)
    rows = labels.merge(metadata, on=["ecg_id", "patient_id", "filename_hr"], validate="one_to_one")
    rows = rows.merge(fit, on=["ecg_id", "patient_id", "filename_hr", "strat_fold"], validate="one_to_one")
    if len(rows) != len(labels) or not pd.to_numeric(rows["strat_fold"]).between(1, 7).all():
        raise ValueError("PTB training metadata/identity mismatch")
    current_targets = read_selected_csv(input_root / SCREEN_ROWS, "ecg_id", allowed, ("ecg_id", "target"))
    current_targets["ecg_id"] = current_targets["ecg_id"].map(canonical_integral_id)
    current_targets = current_targets.rename(columns={"target": "screen_target"})
    rows = rows.merge(current_targets, on="ecg_id", validate="one_to_one")
    old_targets = pd.to_numeric(rows["target"], errors="raise")
    current = pd.to_numeric(rows["screen_target"], errors="raise")
    if len(rows) != len(labels) or not old_targets.eq(current).all():
        raise ValueError("Original PTB targets disagree with current SCREEN-01 targets")
    rows["record_id"] = "ptbxl:" + rows["ecg_id"]
    rows = rows.merge(quality, on="record_id", suffixes=("", "_quality"), validate="one_to_one")
    if len(rows) != len(labels) or not ("ptbxl:" + rows["patient_id"]).eq(rows["patient_id_quality"]).all():
        raise ValueError("PTB quality patient identity mismatch")
    if not rows["path"].eq("data/raw/ptb-xl/1.0.3/" + rows["filename_hr"]).all():
        raise ValueError("PTB quality waveform identity mismatch")
    if not rows["strat_fold"].eq(rows["strat_fold_quality"]).all():
        raise ValueError("PTB quality fold identity mismatch")
    rows = ptb_label_evidence(rows, policy["ptbxl"])
    rows = rows.join(normalize_age(rows.pop("age"), True))
    rows = rows.assign(source="ptbxl", family="ptbxl", split="train", record=rows["ecg_id"],
                       patient_id="ptbxl:" + rows["patient_id"], patient_identity_known=True,
                       quality_passed=rows["exclusion_reasons"].eq(""),
                       full_signal_sha256="", waveform_path=rows["path"], backend="ptbxl_wfdb",
                       window_start=0, samples=5000, label_definition="diagnostic_abnormality")
    rows["target"] = pd.to_numeric(rows["target"], errors="raise")
    ledger = ptb_initial_exclusions(quality, {"ptbxl:" + value for value in allowed}, set(rows["record_id"]))
    counts = {"original_quality_rows": len(quality), "defined_current_fit_labels": len(rows),
              "original_quality_excluded": int(quality["exclusion_reasons"].ne("").sum()),
              "not_current_fit_or_undefined": len(ledger),
              "screen_target_comparison_rows": len(rows), "screen_target_disagreements": 0,
              "excluded_quality": int((~rows["quality_passed"]).sum()),
              "excluded_label_evidence": int((rows["label_evidence_rank"] < 0).sum())}
    return rows, hashes, counts, ledger


def load_challenge(input_root: Path, policy: dict[str, Any]) -> tuple[pd.DataFrame, dict[str, str], dict]:
    """Consume only completed strict-window training evidence under the original split gate."""
    if sha256_file(input_root / SPLIT_ROWS) != SPLIT_SHA256:
        raise ValueError("Original Challenge split bytes have not been recovered")
    rows, receipt, hashes = verified_table(input_root, CHALLENGE_QUALITY, "training_quality", True)
    hashes[stored(SPLIT_ROWS)] = SPLIT_SHA256
    if len(rows) != receipt["records"] or not rows["split"].eq("train").all():
        raise ValueError("Challenge quality table must contain exactly its declared training records")
    allowed = parse_boolean(rows["supervised_eligible"])
    if not rows.loc[allowed, "samples"].eq("5000").all():
        raise ValueError("Longer-record crops cannot inherit supervised record labels")
    if not rows.loc[allowed, "quality_status"].eq("passed").all():
        raise ValueError("Supervised eligibility contradicts quality evidence")
    rows = rows.assign(target=pd.to_numeric(rows["supervised_target"], errors="coerce"),
                       quality_passed=rows["quality_status"].eq("passed"),
                       supervised_admitted=allowed)
    rows["full_signal_sha256"] = rows["full_signal_sha256"].fillna("")
    rows["signal_sha256"] = rows["signal_window_sha256"]
    raw_age = rows.pop("age_raw")
    rows = rows.drop(columns="age").join(normalize_age(raw_age, False))
    evidence = rows["source"].map(policy["sources"])
    rows["label_evidence_rank"] = evidence.map(lambda item: item["rank"] if isinstance(item, dict) else -1)
    rows["label_evidence"] = evidence.map(lambda item: item["evidence"] if isinstance(item, dict) else "")
    rows["label_evidence_reference"] = evidence.map(
        lambda item: item["reference"] if isinstance(item, dict) else "")
    rows["label_evidence_scope"] = "source_process"
    rows["patient_identity_known"] = parse_boolean(rows["patient_identity_known"])
    rows["label_definition"] = "challenge_primary_MI_STTC_CD_HYP_vs_sinus_only"
    return rows, hashes, {"training_rows": len(rows), "supervised_eligible": int(allowed.sum())}
