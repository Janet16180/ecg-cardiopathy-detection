def fill_by_group(values: pd.Series, groups: list[pd.Series]) -> pd.Series:
    """
    Fill missing values with the median of their group, then the overall median.

    Parameters
    ----------
    values : pd.Series
        Numeric values with gaps.
    groups : list[pd.Series]
        Grouping columns aligned with ``values``.

    Returns
    -------
    pd.Series
        Values without gaps.
    """
    medians = values.groupby(groups, observed=True).transform("median")
    return values.fillna(medians).fillna(values.median())


def group_rare(values: pd.Series, min_share: float) -> pd.Series:
    """
    Merge categories rarer than a share of records into ``other``.

    Parameters
    ----------
    values : pd.Series
        Categorical values without gaps.
    min_share : float
        Smallest share of records a category needs to be kept.

    Returns
    -------
    pd.Series
        Values with rare categories replaced by ``other``.
    """
    shares = values.value_counts(normalize=True)
    return values.where(values.map(shares).ge(min_share), "other")


def coded_category(values: pd.Series) -> pd.Series:
    """
    Turn a float-coded ID column into strings, with ``unknown`` for gaps.

    Parameters
    ----------
    values : pd.Series
        IDs stored as floats with NaN.

    Returns
    -------
    pd.Series
        String category per record.
    """
    return values.map(lambda value: "unknown" if pd.isna(value) else str(int(value)))


def clean_demographics(meta: pd.DataFrame) -> tuple[pd.DataFrame, list[dict]]:
    """
    Clean age, sex, height and weight.

    Age 300 becomes 90 with a flag. Implausible adult heights, weights and
    body mass indices become missing, and the gaps are then filled with the
    median of the sex and age band, keeping a flag of what was observed.

    Parameters
    ----------
    meta : pd.DataFrame
        Output of ``load_metadata``.

    Returns
    -------
    tuple[pd.DataFrame, list[dict]]
        Clean columns indexed like ``meta``, and one log row per step.
    """
    flags = implausible_rows(meta)
    bad_bmi = flags["BMI < 12 or > 70"]
    bad_height = flags["adult height < 120 cm"] | bad_bmi
    bad_weight = flags["adult weight < 30 kg"] | bad_bmi
    clean = pd.DataFrame({
        "age": meta["age"].clip(upper=90),
        "age_over_89": meta["age"].eq(300),
        "male": meta["sex"].eq(0),
        "height": meta["height"].mask(bad_height),
        "weight": meta["weight"].mask(bad_weight),
    }, index=meta.index)
    clean["age_band"] = age_band(clean["age"])
    clean["bmi"] = clean["weight"] / (clean["height"] / 100) ** 2
    clean["height_observed"] = clean["height"].notna()
    clean["weight_observed"] = clean["weight"].notna()
    groups = [clean["male"], clean["age_band"]]
    clean["height_filled"] = fill_by_group(clean["height"], groups)
    clean["weight_filled"] = fill_by_group(clean["weight"], groups)
    log = [
        {"column": "age", "problem": "300 is a placeholder for over 89",
         "action": "set to 90, flag age_over_89", "records": int(clean["age_over_89"].sum())},
        {"column": "height", "problem": "implausible adult value or BMI",
         "action": "set to missing", "records": int((bad_height & meta["height"].notna()).sum())},
        {"column": "weight", "problem": "implausible adult value or BMI",
         "action": "set to missing", "records": int((bad_weight & meta["weight"].notna()).sum())},
        {"column": "height", "problem": "missing",
         "action": "flag height_observed, fill height_filled with sex and age-band median",
         "records": int((~clean["height_observed"]).sum())},
        {"column": "weight", "problem": "missing",
         "action": "flag weight_observed, fill weight_filled with sex and age-band median",
         "records": int((~clean["weight_observed"]).sum())},
    ]
    return clean, log


def clean_annotations(meta: pd.DataFrame, min_site_share: float = 0.01) -> tuple[pd.DataFrame, list[dict]]:
    """
    Clean the acquisition and annotation columns.

    Free-text noise columns become presence flags, coded IDs become
    categories with ``unknown`` for gaps, rare sites are merged, and
    ``not recorded`` replaces a missing heart axis.

    Parameters
    ----------
    meta : pd.DataFrame
        Output of ``load_metadata``.
    min_site_share : float
        Sites below this share of records are merged into ``other``.

    Returns
    -------
    tuple[pd.DataFrame, list[dict]]
        Clean columns indexed like ``meta``, and one log row per step.
    """
    clean = pd.DataFrame({
        "device": meta["device"].str.split().str.join(" "),
        "nurse": coded_category(meta["nurse"]),
        "site": group_rare(coded_category(meta["site"]), min_site_share),
        "validated_by": coded_category(meta["validated_by"]),
        "heart_axis": meta["heart_axis"].fillna("not recorded"),
        "infarction_stadium": meta["infarction_stadium1"].fillna("none"),
        "validated_by_human": meta["validated_by_human"],
        "second_opinion": meta["second_opinion"],
        "recording_date": meta["recording_date"],
        "year": meta["recording_date"].dt.year,
        "strat_fold": meta["strat_fold"],
        "patient_id": meta["patient_id"].astype(int),
        "filename_hr": meta["filename_hr"],
    }, index=meta.index)
    for column in QUALITY_COLUMNS:
        clean[f"has_{column}"] = meta[column].notna()
    texts = ", ".join(f"{column} ({meta[column].nunique()})" for column in QUALITY_COLUMNS)
    log = [
        {"column": "baseline_drift ... pacemaker", "problem": f"free text, distinct values: {texts}",
         "action": "replace by presence flags has_*",
         "records": int(meta[QUALITY_COLUMNS].notna().any(axis=1).sum())},
        {"column": "nurse, site, validated_by", "problem": "float-coded IDs with gaps",
         "action": "convert to categories, gaps become unknown",
         "records": int(meta[["nurse", "site", "validated_by"]].isna().any(axis=1).sum())},
        {"column": "site", "problem": f"{meta['site'].nunique()} sites, most with few records",
         "action": f"merge sites under {min_site_share:.0%} of records into other",
         "records": int(clean["site"].eq("other").sum())},
        {"column": "heart_axis", "problem": "missing when not annotated",
         "action": "new category not recorded", "records": int(meta["heart_axis"].isna().sum())},
        {"column": "infarction_stadium1", "problem": "missing when there is no infarction",
         "action": "new category none", "records": int(meta["infarction_stadium1"].isna().sum())},
        {"column": "infarction_stadium2",
         "problem": f"{meta['infarction_stadium2'].isna().mean():.1%} missing",
         "action": "drop", "records": len(meta)},
        {"column": "device", "problem": "names padded with spaces",
         "action": "collapse whitespace", "records": int(meta["device"].ne(clean["device"]).sum())},
        {"column": "report", "problem": f"free text, {meta['report'].nunique()} distinct values",
         "action": "drop (scp_codes encode the same reading)", "records": len(meta)},
        {"column": "filename_lr", "problem": "smoothed copy of the 500 Hz file",
         "action": "drop, keep filename_hr", "records": len(meta)},
    ]
    return clean, log


def clean_labels(meta: pd.DataFrame, classes: dict[str, str]) -> tuple[pd.DataFrame, list[dict]]:
    """
    Reduce the 71 SCP statements to superclass flags and the project label.

    Parameters
    ----------
    meta : pd.DataFrame
        Output of ``load_metadata`` joined with ``superclass_flags``.
    classes : dict[str, str]
        Output of ``diagnostic_classes``.

    Returns
    -------
    tuple[pd.DataFrame, list[dict]]
        Clean columns indexed like ``meta``, and one log row per step.
    """
    clean = meta[[*SUPERCLASSES, "abnormal"]].copy()
    clean["statements"] = meta["scp_codes"].apply(len)
    clean["label"] = meta["scp_codes"].apply(project_label, classes=classes)
    codes = len({code for listed in meta["scp_codes"] for code in listed})
    log = [
        {"column": "scp_codes", "problem": f"{codes} distinct statements, several per record",
         "action": "five superclass flags, statement count and the binary label",
         "records": len(meta)},
        {"column": "label", "problem": "NORM mixed with other statements, or no diagnostic statement",
         "action": "left unlabeled (NaN)", "records": int(clean["label"].isna().sum())},
    ]
    return clean, log


def clean_signals(summary: pd.DataFrame) -> tuple[pd.DataFrame, list[dict]]:
    """
    Keep the signal measures and flag records with signal problems.

    Parameters
    ----------
    summary : pd.DataFrame
        Output of ``ptbxl_summary``.

    Returns
    -------
    tuple[pd.DataFrame, list[dict]]
        Signal columns indexed like ``summary``, and one log row per step.
    """
    limb = summary[["einthoven_residual", "avf_residual", "avl_residual", "avr_residual"]].max(axis=1)
    measures = ["heart_rate", "std", "baseline_fraction", "high_frequency_fraction", "peak_abs_mv"]
    clean = summary[measures].rename(columns={"std": "signal_std"})
    clean["dead_lead"] = summary["constant_leads"] > 0
    clean["spike_over_10mv"] = summary["large_leads"] > 0
    clean["limb_identity_violated"] = limb > 0.05
    log = [
        {"column": "signal", "problem": "a lead constant for the whole record",
         "action": "drop the record", "records": int(clean["dead_lead"].sum())},
        {"column": "signal", "problem": "artifact spike above 10 mV",
         "action": "keep, flag spike_over_10mv", "records": int(clean["spike_over_10mv"].sum())},
        {"column": "signal", "problem": "limb-lead identity off by more than 0.05 mV",
         "action": "keep, flag limb_identity_violated",
         "records": int(clean["limb_identity_violated"].sum())},
        {"column": "heart_rate", "problem": "not estimated",
         "action": "left missing", "records": int(clean["heart_rate"].isna().sum())},
    ]
    return clean, log


def clean_metadata(meta: pd.DataFrame, classes: dict[str, str],
                   summary: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    """
    Apply every preprocessing step and return the clean table with its log.

    Parameters
    ----------
    meta : pd.DataFrame
        Output of ``load_metadata`` joined with ``superclass_flags``.
    classes : dict[str, str]
        Output of ``diagnostic_classes``.
    summary : pd.DataFrame
        Output of ``ptbxl_summary``.

    Returns
    -------
    tuple[pd.DataFrame, pd.DataFrame]
        One row per kept record, and one row per preprocessing step with the
        number of records it touched.
    """
    parts = [clean_demographics(meta), clean_annotations(meta), clean_labels(meta, classes),
             clean_signals(summary.loc[meta.index])]
    clean = pd.concat([part for part, _ in parts], axis=1)
    log = pd.DataFrame([row for _, rows in parts for row in rows])
    clean = clean[~clean["dead_lead"]].drop(columns="dead_lead")
    clean["label"] = clean["label"].astype(float)
    clean["bmi"] = clean["bmi"].replace([np.inf, -np.inf], np.nan)
    return clean, log
