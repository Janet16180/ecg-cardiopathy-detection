"""Experiment 035, descriptive stage: what the hard added subset and the Challenge training labels are.

Reads metadata and labels only: PTB-XL SCP codes, devices, ages and axes, the Challenge SNOMED codes of the
frozen split's training rows and 022b's kept training rows. No feature, model or score is read.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from ecg_experiment.eda import challenge
from ecg_experiment.eda.ptbxl import diagnostic_classes, load_metadata, load_statements, superclasses
from ecg_experiment.files import sha256_file, write_json_atomic
from ecg_experiment.full_development import cohorts, ptb_table
from ecg_experiment.hard_subset import (
    LABEL_RULES,
    PTBXL_COMPATIBLE,
    SINUS_CODES,
    code_counts,
    ptbxl_under_challenge,
    rule_labels,
)
from scripts.experiments.run_multisource_manifold026b import FEATURES, NINGBO, SOURCES_ORDER, SPLITS
from scripts.experiments.run_multisource_readout022b import OUTPUT as PRIOR022B

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "outputs/experiment035_hard_subset_v1"
KEPT_DUPLICATES = ("unique", "kept")


def ptbxl_groups() -> tuple[dict[str, pd.DataFrame], pd.DataFrame, dict[str, str]]:
    """
    PTB-XL development and training rows with a standard label, split into the descriptive groups.

    Returns
    -------
    tuple[dict[str, pd.DataFrame], pd.DataFrame, dict[str, str]]
        Rows per group, the PTB-XL metadata and the diagnostic superclass of each SCP code.
    """
    table = ptb_table()
    groups = cohorts(table)
    meta = load_metadata()
    classes = diagnostic_classes(load_statements())
    development = groups["development"][groups["development"]["standard"].notna()]
    train = groups["train"][groups["train"]["standard"].notna()]
    dropped = train["target"].isna()
    parts = {"hard": development[~development["original"]], "ordinary": development[development["original"]],
             "train_dropped": train[dropped], "train_kept": train[~dropped]}
    named = {}
    for name, rows in parts.items():
        for label, suffix in ((0, "negative"), (1, "positive")):
            named[f"{name}_{suffix}"] = rows[rows["standard"] == label]
    return named, meta, classes


def describe_ptbxl(rows: pd.DataFrame, meta: pd.DataFrame, classes: dict[str, str]) -> dict[str, Any]:
    """
    Codes, superclasses, devices, demographics and Challenge-style labels of one PTB-XL group.

    Parameters
    ----------
    rows : pd.DataFrame
        Rows of ``full_development.ptb_table`` for the group.
    meta : pd.DataFrame
        ``eda.ptbxl.load_metadata`` output.
    classes : dict[str, str]
        Diagnostic superclass of each SCP code.

    Returns
    -------
    dict[str, Any]
        Summary counts of the group.
    """
    records = meta.loc[rows["ecg_id"].astype(int)]
    codes = records["scp_codes"].tolist()
    challenge_style = pd.DataFrame([ptbxl_under_challenge(item, classes) for item in codes])
    ages = rows["age"].dropna()
    return {
        "records": len(rows), "patients": int(rows["patient_id"].nunique()),
        "with_norm": int(sum("NORM" in item for item in codes)),
        "codes_besides_norm": code_counts([set(item) - {"NORM"} for item in codes]),
        "superclasses": records["scp_codes"].apply(lambda item: superclasses(item, classes))
        .value_counts().to_dict(),
        "norm_likelihood": {f"{key:g}": int(value) for key, value in
                            pd.Series([item.get("NORM", -1.0) for item in codes]).value_counts().items()},
        "devices": rows["device"].value_counts().to_dict(),
        "heart_axis": records["heart_axis"].fillna("missing").value_counts().to_dict(),
        "age": {"missing": int(rows["age"].isna().sum()), "mean": float(ages.mean()),
                "quartiles": [float(value) for value in ages.quantile([0.25, 0.5, 0.75])]},
        "male_share": float(rows["male"].mean()),
        "autogenerated_report_share": float(records["initial_autogenerated_report"].mean()),
        "challenge_style": {name: {f"{key:g}": int(value) for key, value in
                                   challenge_style[name].value_counts(dropna=False).items()}
                            for name in ("primary", "secondary")},
    }


def challenge_codes() -> dict[tuple[str, str], list[str]]:
    """
    SNOMED codes of every Challenge record, keyed by source and record.

    Returns
    -------
    dict[tuple[str, str], list[str]]
        Codes per ``(source, record)``.
    """
    ningbo = pd.read_csv(NINGBO / "rows.csv", dtype={"record": str, "snomed_codes": str},
                         usecols=["record", "snomed_codes"], keep_default_na=False)
    headers = challenge.load_headers()
    codes = {("ningbo", record): [code for code in text.split(";") if code]
             for record, text in zip(ningbo["record"], ningbo["snomed_codes"], strict=True)}
    codes.update({(source, record): list(items) for source, record, items in
                  zip(headers["source"], headers["record"], headers["dx_codes"], strict=True)})
    return codes


def training_candidates(codes: dict[tuple[str, str], list[str]]) -> pd.DataFrame:
    """
    Challenge training-group rows with features and a kept duplicate status, labeled by every rule.

    Parameters
    ----------
    codes : dict[tuple[str, str], list[str]]
        Output of ``challenge_codes``.

    Returns
    -------
    pd.DataFrame
        Split rows with ``codes``, the split's labels as ``split_primary`` and ``split_secondary``, and one
        label column per rule.
    """
    rows = pd.read_csv(SPLITS / "rows.csv", dtype={"record": str})
    rows = rows[(rows["split"] == "train") & rows["duplicate_status"].isin(KEPT_DUPLICATES)]
    rows = rows.rename(columns={"primary": "split_primary", "secondary": "split_secondary"})
    parts = []
    for source in SOURCES_ORDER:
        with np.load(FEATURES / f"{source}.npz") as saved:
            records = set(saved["record"].astype(str))
        parts.append(rows[(rows["source"] == source) & rows["record"].isin(records)].sort_values("record"))
    candidates = pd.concat(parts, ignore_index=True)
    candidates["codes"] = [codes[(source, record)] for source, record in
                           zip(candidates["source"], candidates["record"], strict=True)]
    for rule in LABEL_RULES:
        candidates[rule] = rule_labels(candidates["codes"], rule)
    return candidates


def describe_challenge(candidates: pd.DataFrame, kept: pd.DataFrame) -> dict[str, Any]:
    """
    Label counts per rule and source, and the rhythm and form codes of 022b's training positives.

    Parameters
    ----------
    candidates : pd.DataFrame
        Output of ``training_candidates``.
    kept : pd.DataFrame
        022b's kept Challenge training rows with ``codes``.

    Returns
    -------
    dict[str, Any]
        Counts before the training quality policy, and code shares among 022b's rows.

    Raises
    ------
    ValueError
        If the ``primary`` or ``secondary`` rule differs from the split's labels.
    """
    for rule in ("primary", "secondary"):
        if not np.array_equal(candidates[rule].to_numpy(), candidates[f"split_{rule}"].to_numpy(),
                              equal_nan=True):
            raise ValueError(f"The {rule} rule differs from the Challenge split's label")
    by_rule = {rule: {source: {"positive": int((part[rule] == 1).sum()),
                               "negative": int((part[rule] == 0).sum())}
                      for source, part in candidates.groupby("source")}
               for rule in LABEL_RULES}
    watched = {"sinus_variant": SINUS_CODES - {"426783006"}, "ptbxl_compatible": PTBXL_COMPATIBLE}
    shares = {}
    for family, part in kept.groupby("family"):
        shares[family] = {}
        for label, name in ((1, "positive"), (0, "negative")):
            members = part[part["primary"] == label]
            shares[family][name] = {"records": len(members), **{
                key: float(np.mean([bool(set(item) & codes) for item in members["codes"]])) if len(members)
                else None for key, codes in watched.items()}}
    return {"candidates_by_rule_before_quality": by_rule, "kept_022b_code_shares": shares,
            "kept_022b_positive_codes": code_counts(kept.loc[kept["primary"] == 1, "codes"])}


def main() -> None:
    """Write the descriptive summary of the hard subset and the Challenge training labels."""
    groups, meta, classes = ptbxl_groups()
    codes = challenge_codes()
    candidates = training_candidates(codes)
    saved = pd.read_csv(PRIOR022B / "training_rows.csv", dtype={"record": str})
    kept = saved[saved["kept"]].copy()
    kept["codes"] = [codes[(source, record)] for source, record in
                     zip(kept["source"], kept["record"], strict=True)]
    result = {
        "ptbxl": {name: describe_ptbxl(rows, meta, classes) for name, rows in groups.items()},
        "challenge": describe_challenge(candidates, kept),
        "inputs_sha256": {"challenge_splits/rows.csv": sha256_file(SPLITS / "rows.csv"),
                          "022b/training_rows.csv": sha256_file(PRIOR022B / "training_rows.csv"),
                          "ningbo/rows.csv": sha256_file(NINGBO / "rows.csv")},
        "sources_sha256": {name: sha256_file(ROOT / name) for name in (
            "ecg_experiment/hard_subset.py", "scripts/experiments/describe_hard_subset035.py")},
        "scores_read": False,
    }
    OUTPUT.mkdir(parents=True, exist_ok=True)
    write_json_atomic(OUTPUT / "descriptive.json", result)
    print(json.dumps({"stage": "complete", "groups": {name: value["records"]
                                                      for name, value in result["ptbxl"].items()}}))


if __name__ == "__main__":
    main()
