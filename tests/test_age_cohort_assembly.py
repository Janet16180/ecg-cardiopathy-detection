def test_full_assembly_filters_current_roles_preserves_targets_and_censored_age(reconstructed_inputs):
    root = reconstructed_inputs
    receipt = assembly.assemble(root, Path("outputs/new"), size=4)
    candidates_table = pd.read_csv(root / "outputs/new/candidates.csv")
    assert set(candidates_table.record_id) == {"ptbxl:1", "ptbxl:2", "ningbo:a", "ningbo:b"}
    assert candidates_table.groupby("source").target.sum().to_dict() == {"ningbo": 1, "ptbxl": 1}
    younger = pd.read_csv(root / "outputs/new/younger.csv")
    assert younger.record_id.tolist() == ["ningbo:a", "ningbo:b", "ptbxl:1", "ptbxl:2"]
    age = receipt["summary"]["all_age"]["age"]
    assert age["right_censored_over_89_count"] == 1
    assert age["exact_mean"] == pytest.approx((20 + 22 + 40) / 3)
    assert receipt["complete"]
    assert receipt["waveforms_read"] == 0
    assert receipt["summary"]["overlap_between_training_cohorts"]["records"] == 4
    assert all(value == 0 for value in receipt["summary"]["evaluation_overlap_after_admission"].values())
    for path, expected in receipt["artifacts"].items():
        assert sha256_file(root / path) == expected
    with pytest.raises(FileExistsError):
        assembly.assemble(root, Path("outputs/new"), size=4)


