def digest(value: str) -> str:
    return hashlib.sha256(value.encode()).hexdigest()


def write_table(root: Path, relative: Path, table: pd.DataFrame) -> str:
    path = root / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    table.to_csv(path, index=False)
    return sha256_file(path)


def write_receipt(root: Path, path: Path, table_path: Path, declared_scope: str, **extra) -> None:
    quality_hash = sha256_file(ROOT / "ecg_experiment/ecg_quality.py")
    value = {
        "complete": True, "scope": declared_scope, "coverage_complete": True, "table_path": str(table_path),
        "table_sha256": sha256_file(root / table_path), "original_split_sha256": inputs.SPLIT_SHA256,
        "source_sha256": {"ecg_experiment/ecg_quality.py": quality_hash},
        **extra,
    }
    (root / path).parent.mkdir(parents=True, exist_ok=True)
    (root / path).write_text(json.dumps(value))


def reference_rows() -> pd.DataFrame:
    return pd.DataFrame([{
        "source": "heldout", "record_id": "heldout:1", "patient_id": "ptbxl:reserved",
        "patient_identity_known": "True", "canonical_sha256": digest("reserved_window"),
        "full_signal_sha256": digest("reserved_full"), "role": "evaluation", "skip_reason": "",
    }])


def candidates() -> pd.DataFrame:
    rows = pd.DataFrame({
        "record_id": ["good", "less_evidence", "target_conflict", "sex_conflict", "ordinary"],
        "label_evidence_rank": [0, 2, 1, 1, 1], "target": [0, 0, 1, 0, 1],
        "sex_normalized": ["M", "M", "M", "F", ""],
    })
    return rows.assign(source="synthetic", signal_sha256=digest("shared"))


def test_duplicates_keep_best_evidence_and_reject_conflicting_labels_or_known_sex():
    rows = candidates()
    keep, excluded = assembly.deduplicate_candidates(rows.iloc[:2])
    assert keep.record_id.tolist() == ["good"]
    assert excluded.reason.tolist() == ["duplicate_copy"]
    for other in (2, 3):
        keep, excluded = assembly.deduplicate_candidates(rows.iloc[[0, other]])
        assert keep.empty
        assert excluded.reason.eq("duplicate_conflicting_target_or_known_sex").all()
    unknown = rows.iloc[[0, 4]].assign(target=0)
    assert len(assembly.deduplicate_candidates(unknown)[0]) == 1


def test_evaluation_identity_checks_cover_records_patients_windows_and_full_signals():
    rows = pd.DataFrame({
        "record_id": ["heldout:1", "patient", "window", "full", "safe"],
        "patient_id": ["", "ptbxl:reserved", "", "", ""],
        "signal_sha256": [digest(str(i)) for i in range(5)],
        "full_signal_sha256": ["", "", "", digest("reserved_full"), ""],
    }).assign(split="train", quality_passed=True, target=0, label_evidence_rank=1, supervised_admitted=True)
    rows.loc[2, "signal_sha256"] = digest("reserved_window")
    actual = assembly.exclusion_reasons(rows, reference_rows()).tolist()
    assert actual == [
        "heldout_record", "heldout_patient", "heldout_canonical_window", "heldout_full_signal", "",
    ]
    assert assembly.evaluation_overlap(rows.iloc[4:], reference_rows()) == {
        "records": 0, "known_patients": 0, "canonical_windows": 0, "full_signals": 0,
    }


def test_ptb_privacy_ages_are_censored_bounds_and_not_exact_ninety_year_olds():
    raw = pd.Series(["20", "300", "89", "-1", "", "121", "0", "inf"])
    ages = inputs.normalize_age(raw, True)
    assert ages.age.iloc[:3].tolist() == [20, 90, 89]
    assert ages.age_right_censored.tolist() == [False, True, False, False, False, False, False, False]
    assert ages.age_missing.sum() == 4
    assert ages.age_raw.iloc[1] == "300"
    assert np.isnan(inputs.normalize_age(pd.Series(["0"]), False).age.iloc[0])


def test_label_evidence_does_not_promote_unvalidated_automatic_or_unknown_reports():
    raw = pd.DataFrame({"validated_by_human": ["True", "False", "", "False"],
                        "initial_autogenerated_report": ["True", "False", "", "True"]})
    policy = json.loads((ROOT / inputs.POLICY).read_text())
    result = inputs.ptb_label_evidence(raw, policy["ptbxl"])
    assert result.label_evidence_rank.tolist() == [1, 2, -1, -1]
    assert result.label_evidence.tolist() == ["record_human_validated", "record_physician_origin", "", ""]


@pytest.mark.parametrize(("field", "value"), [("complete", False), ("scope", "resource_profile")])
def test_incomplete_or_profile_receipts_cannot_admit_records(tmp_path, field, value):
    table = Path("rows.csv")
    write_table(tmp_path, table, pd.DataFrame({"a": [1]}))
    write_receipt(tmp_path, Path("receipt.json"), table, "training_quality", **{field: value})
    with pytest.raises(ValueError, match="Incomplete|wrong-scope"):
        inputs.verified_table(tmp_path, Path("receipt.json"), "training_quality", False)


def test_changed_table_and_changed_quality_policy_are_rejected(tmp_path):
    table = Path("rows.csv")
    write_table(tmp_path, table, pd.DataFrame({"a": [1]}))
    path = Path("receipt.json")
    write_receipt(tmp_path, path, table, "training_quality")
    (tmp_path / table).write_text("a\n2\n")
    with pytest.raises(ValueError, match="table changed"):
        inputs.verified_table(tmp_path, path, "training_quality", False)
    write_receipt(tmp_path, path, table, "training_quality",
                  source_sha256={"ecg_experiment/ecg_quality.py": "x"})
    with pytest.raises(ValueError, match="quality policy"):
        inputs.verified_table(tmp_path, path, "training_quality", False)


def test_reference_gate_requires_patient_identity_and_explicit_missing_view_reason(tmp_path):
    table = inputs.REFERENCES.parent / "reference_rows.csv"
    refs = reference_rows().drop(columns="patient_id")
    write_table(tmp_path, table, refs)
    write_receipt(tmp_path, inputs.REFERENCES, table, "mechanical_reference_recovery")
    with pytest.raises(ValueError, match="schema"):
        inputs.read_references(tmp_path)
    refs = reference_rows().assign(canonical_sha256="")
    write_table(tmp_path, table, refs)
    write_receipt(tmp_path, inputs.REFERENCES, table, "mechanical_reference_recovery")
    with pytest.raises(ValueError, match="skip reason"):
        inputs.read_references(tmp_path)
    write_table(tmp_path, table, reference_rows())
    write_receipt(tmp_path, inputs.REFERENCES, table, "mechanical_reference_recovery",
                  coverage_complete=False)
    with pytest.raises(ValueError, match="coverage is incomplete"):
        inputs.read_references(tmp_path)


